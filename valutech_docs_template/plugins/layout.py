"""MkDocs plugin: page width for large screens.

Material for MkDocs caps the whole layout — header, tabs, content, footer — at
``61rem`` (1220 px), which leaves most of a large monitor empty and squeezes
wide tables and diagrams. This plugin raises that cap and, on large screens,
widens the navigation sidebars so long page titles wrap less.

Enabled in the base configuration; a consuming project tunes or reverts it::

    plugins:
      valutech-layout:
        width: wide          # default | wide | full
        max_width: 90rem     # optional, overrides the width preset
        sidebar_width: 14rem # optional, "" keeps Material's 12.1rem

Only the web build is affected — the PDF has its own page layout.
"""

from __future__ import annotations

import re

from mkdocs.config import config_options
from mkdocs.exceptions import PluginError
from mkdocs.plugins import BasePlugin
from mkdocs.structure.files import File

from .. import __version__

ASSET_URI = "assets/valutech/layout.css"

WIDTHS = {"default": None, "wide": "80rem", "full": "none"}
"""Presets for `.md-grid` max-width. Material scales rem up on large screens
(137.5 % from 1600 px, 150 % from 2000 px), so `80rem` grows with them."""

LENGTH = re.compile(r"^(none|\d+(\.\d+)?(rem|em|px|%|vw))$")

LARGE_SCREEN = "100em"
"""Material's own breakpoint for its largest font scale step (1600 px)."""


class LayoutPlugin(BasePlugin):
    """Injects a generated stylesheet that widens the Material layout."""

    config_scheme = (
        ("width", config_options.Choice(tuple(WIDTHS), default="wide")),
        ("max_width", config_options.Type(str, default="")),
        ("sidebar_width", config_options.Type(str, default="14rem")),
    )

    def __init__(self) -> None:
        super().__init__()
        self._css = ""

    def on_config(self, config):
        for key in ("max_width", "sidebar_width"):
            value = self.config[key].strip()
            if value and not LENGTH.match(value):
                raise PluginError(f"valutech-layout: {key} {value!r} is not a CSS length like 90rem or 1600px")

        self._css = self._stylesheet()
        if self._css:
            config["extra_css"].append(f"{ASSET_URI}?v={__version__}")
        return config

    def on_files(self, files, config):
        if self._css:
            files.append(File.generated(config, ASSET_URI, content=self._css))
        return files

    def _stylesheet(self) -> str:
        width = self.config["max_width"].strip() or WIDTHS[self.config["width"]]
        if not width:
            return ""

        css = [
            "/* Generated by the valutech-layout plugin. */",
            f".md-grid {{\n  max-width: {width};\n}}",
        ]
        if width == "none":
            # Without a cap, keep the header and content off the screen edge.
            css.append(".md-grid {\n  padding-left: 1rem;\n  padding-right: 1rem;\n}")

        sidebar = self.config["sidebar_width"].strip()
        if sidebar:
            css.append(
                f"@media screen and (min-width: {LARGE_SCREEN}) {{\n"
                f"  .md-sidebar {{\n    width: {sidebar};\n  }}\n"
                "}"
            )
        return "\n\n".join(css) + "\n"
